//! Username/password authentication backed by the database.
//!
//! This module provides an authentication backend, [`PasswordUserBackend`],
//! that checks usernames and passwords stored in the database using the Cot
//! ORM. The credentials are stored in the [`PasswordUser`] model, which
//! references the [canonical user](crate::auth::canonical::CanonicalUser) of
//! the project; the canonical user itself is defined by the project.
//!
//! To use it, register [`PasswordUserApp`] (which creates the table for the
//! credentials) and return [`PasswordUserBackend`] from
//! [`Project::auth_backends`](crate::Project::auth_backends).

use std::fmt::{Debug, Formatter};
use std::marker::PhantomData;

use async_trait::async_trait;
// Importing `Auto` from `cot` instead of `crate` so that the migration
// generator can figure out it's an autogenerated field
use cot::db::Auto;
use thiserror::Error;

use crate::App;
use crate::auth::backend::{AuthenticationBackendCommon, UsernamePasswordBackend};
use crate::auth::canonical::CanonicalUser;
use crate::auth::{
    AuthError, PasswordHash, PasswordVerificationResult, Result, SessionAuthHash, UserId,
};
use crate::common_types::Password;
use crate::config::SecretKey;
use crate::db::migrations::SyncDynMigration;
use crate::db::{Database, DatabaseBackend, LimitedString, Model, model, query};

pub mod migrations;

pub(crate) const MAX_USERNAME_LENGTH: u32 = 255;

/// The username and password of a user.
///
/// Each [canonical user](CanonicalUser) has at most one username and password.
/// The table is created by [`PasswordUserApp`], with a foreign key to the table
/// of the canonical user of the project, so when the user is deleted, their
/// credentials are deleted as well.
///
/// # Examples
///
/// ```
/// use cot::auth::user_pass::PasswordUser;
/// use cot::common_types::Password;
/// use cot::db::{Database, Model};
/// # use cot::test::TestUser as MyUser;
///
/// async fn sign_up(db: &Database) -> cot::Result<()> {
///     let mut user = MyUser::new();
///     user.insert(db).await?;
///
///     PasswordUser::create(db, &user, "testuser", &Password::new("password123"))
///         .await?;
///     Ok(())
/// }
///
/// # #[tokio::main]
/// # async fn main() -> cot::Result<()> {
/// #     use cot::test::TestDatabase;
/// #     let mut test_database = TestDatabase::new_sqlite().await?;
/// #     test_database.with_test_user().with_auth::<MyUser>().run_migrations().await;
/// #     sign_up(&test_database.database()).await?;
/// #     test_database.cleanup().await?;
/// #     Ok(())
/// # }
/// ```
#[derive(Debug, Clone)]
#[model]
pub struct PasswordUser {
    #[model(primary_key)]
    id: Auto<i64>,
    #[model(unique)]
    user: i64,
    #[model(unique)]
    username: LimitedString<MAX_USERNAME_LENGTH>,
    password: PasswordHash,
}

/// An error that occurs when creating a user.
#[derive(Debug, Clone, Error)]
#[non_exhaustive]
pub enum CreateUserError {
    /// The username is too long.
    #[error("username is too long (max {MAX_USERNAME_LENGTH} characters, got {0})")]
    UsernameTooLong(usize),
}

impl PasswordUser {
    /// Creates the credentials of the given user and saves them to the
    /// database.
    ///
    /// # Errors
    ///
    /// Returns [`AuthError::UserNotFound`] if the user hasn't been saved to the
    /// database yet.
    ///
    /// Returns an error if the username is too long, or if the credentials
    /// could not be saved (for instance, because the username is already
    /// taken, or the user already has credentials).
    pub async fn create<U: CanonicalUser, DB: DatabaseBackend>(
        mut db: DB,
        user: &U,
        username: impl Into<String>,
        password: &Password,
    ) -> Result<Self> {
        let user_id = Self::user_id_of(user)?;
        let mut credentials = Self {
            id: Auto::auto(),
            user: user_id,
            username: Self::convert_username(username)?,
            password: PasswordHash::from_password(password),
        };
        credentials
            .insert(&mut db)
            .await
            .map_err(AuthError::backend_error)?;

        Ok(credentials)
    }

    /// Returns the credentials of the given user, if they have any.
    ///
    /// # Errors
    ///
    /// Returns [`AuthError::UserNotFound`] if the user hasn't been saved to the
    /// database yet.
    ///
    /// Returns an error if the credentials could not be loaded.
    pub async fn get_by_user<U: CanonicalUser, DB: DatabaseBackend>(
        db: DB,
        user: &U,
    ) -> Result<Option<Self>> {
        Self::get_by_user_id(db, Self::user_id_of(user)?).await
    }

    /// Returns the credentials with the given username, if they exist.
    ///
    /// # Errors
    ///
    /// Returns an error if the username is too long, or if the credentials
    /// could not be loaded.
    pub async fn get_by_username<DB: DatabaseBackend>(
        mut db: DB,
        username: &str,
    ) -> Result<Option<Self>> {
        let username = Self::convert_username(username)?;
        query!(PasswordUser, $username == username)
            .get(&mut db)
            .await
            .map_err(AuthError::backend_error)
    }

    pub(crate) async fn get_by_user_id<DB: DatabaseBackend>(
        mut db: DB,
        user_id: i64,
    ) -> Result<Option<Self>> {
        query!(PasswordUser, $user == user_id)
            .get(&mut db)
            .await
            .map_err(AuthError::backend_error)
    }

    /// Checks the given credentials.
    ///
    /// Returns the matching credentials (which contain the
    /// [ID of the user](Self::user_id)) if the username exists and the
    /// password is correct, or [`None`] otherwise. If the password hash is
    /// obsolete, it is upgraded and saved.
    ///
    /// # Errors
    ///
    /// Returns an error if the username is too long, or if the credentials
    /// could not be loaded or saved.
    pub async fn authenticate<DB: DatabaseBackend>(
        mut db: DB,
        credentials: &PasswordUserCredentials,
    ) -> Result<Option<Self>> {
        let user_password = Self::get_by_username(&mut db, credentials.username()).await?;

        if let Some(mut user_password) = user_password {
            match user_password.password.verify(credentials.password()) {
                PasswordVerificationResult::Ok => Ok(Some(user_password)),
                PasswordVerificationResult::OkObsolete(new_hash) => {
                    user_password.password = new_hash;
                    user_password
                        .save(&mut db)
                        .await
                        .map_err(AuthError::backend_error)?;
                    Ok(Some(user_password))
                }
                PasswordVerificationResult::Invalid => Ok(None),
            }
        } else {
            // SECURITY: If no user was found, run the same hashing function to
            // prevent timing attacks from being used to determine if a user
            // exists. Additionally, do something with the result to prevent the
            // compiler from optimizing out the operation.
            // TODO: benchmark this to make sure it works as expected
            let dummy_hash = PasswordHash::from_password(credentials.password());
            if let PasswordVerificationResult::Invalid = dummy_hash.verify(credentials.password()) {
                unreachable!(
                    "Password hash verification should never fail for a newly generated hash"
                );
            }
            Ok(None)
        }
    }

    /// Returns the primary key of the canonical user these credentials belong
    /// to.
    #[must_use]
    pub fn user_id(&self) -> i64 {
        self.user
    }

    /// Returns the username.
    #[must_use]
    pub fn username(&self) -> &str {
        &self.username
    }

    /// Changes the username.
    ///
    /// Note that this doesn't save the change to the database; use
    /// [`Model::save`] for that.
    ///
    /// # Errors
    ///
    /// Returns an error if the username is too long.
    pub fn set_username(&mut self, username: impl Into<String>) -> Result<()> {
        self.username = Self::convert_username(username)?;
        Ok(())
    }

    /// Changes the password.
    ///
    /// This logs the user out of all their sessions once the change is saved.
    /// Note that this doesn't save the change to the database; use
    /// [`Model::save`] for that.
    pub fn set_password(&mut self, password: &Password) {
        self.password = PasswordHash::from_password(password);
    }

    fn user_id_of<U: CanonicalUser>(user: &U) -> Result<i64> {
        match user.id() {
            Some(UserId::Int(id)) => Ok(id),
            Some(UserId::String(_)) => Err(AuthError::UserIdTypeNotSupported),
            None => Err(AuthError::UserNotFound),
        }
    }

    fn convert_username(username: impl Into<String>) -> Result<LimitedString<MAX_USERNAME_LENGTH>> {
        let username = username.into();
        let username_length = username.len();
        LimitedString::new(username).map_err(|_| {
            AuthError::backend_error(CreateUserError::UsernameTooLong(username_length))
        })
    }

    fn session_auth_hash(&self, secret_key: &SecretKey) -> SessionAuthHash {
        const SESSION_AUTH_HASH_CONTEXT: &str = "cot.rs session auth hash v1";

        let key = blake3::derive_key(SESSION_AUTH_HASH_CONTEXT, secret_key.as_bytes());
        let hash = blake3::keyed_hash(&key, self.password.as_str().as_bytes());

        SessionAuthHash::new(hash.as_slice())
    }
}

/// Credentials for authenticating a user stored in the database.
///
/// This struct is used to authenticate a user stored in the database. It
/// contains the username and password of the user.
///
/// Can be passed to [`PasswordUser::authenticate`] to check the
/// password of a user.
#[derive(Debug, Clone)]
pub struct PasswordUserCredentials {
    username: String,
    password: Password,
}

impl PasswordUserCredentials {
    /// Create a new instance of the database user credentials.
    ///
    /// # Example
    ///
    /// ```
    /// use cot::auth::user_pass::PasswordUserCredentials;
    /// use cot::common_types::Password;
    ///
    /// let credentials =
    ///     PasswordUserCredentials::new(String::from("testuser"), Password::new("password123"));
    /// ```
    #[must_use]
    pub fn new(username: String, password: Password) -> Self {
        Self { username, password }
    }

    /// Returns the username of the user.
    ///
    /// # Example
    ///
    /// ```
    /// use cot::auth::user_pass::PasswordUserCredentials;
    /// use cot::common_types::Password;
    ///
    /// let credentials =
    ///     PasswordUserCredentials::new(String::from("testuser"), Password::new("password123"));
    /// assert_eq!(credentials.username(), "testuser");
    /// ```
    #[must_use]
    pub fn username(&self) -> &str {
        &self.username
    }

    /// Returns the password of the user.
    ///
    /// # Example
    ///
    /// ```
    /// use cot::auth::user_pass::PasswordUserCredentials;
    /// use cot::common_types::Password;
    ///
    /// let credentials =
    ///     PasswordUserCredentials::new(String::from("testuser"), Password::new("password123"));
    /// assert!(!credentials.password().as_str().is_empty());
    /// ```
    #[must_use]
    pub fn password(&self) -> &Password {
        &self.password
    }
}

/// The authentication backend for usernames and passwords stored in the
/// database.
///
/// This is the default username/password authentication backend for Cot. It
/// checks the credentials stored in the [`PasswordUser`] model and
/// resolves them to the canonical user `U` of the project. It requires
/// [`PasswordUserApp<U>`] to be registered.
///
/// The session authentication hash is derived from the password hash, so
/// changing the password of a user logs them out of all their sessions.
pub struct PasswordUserBackend<U> {
    database: Database,
    _user: PhantomData<fn() -> U>,
}

impl<U> Debug for PasswordUserBackend<U> {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("PasswordUserBackend")
            .field("database", &self.database)
            .field("user", &std::any::type_name::<U>())
            .finish()
    }
}

impl<U> Clone for PasswordUserBackend<U> {
    fn clone(&self) -> Self {
        Self::new(self.database.clone())
    }
}

impl<U> PasswordUserBackend<U> {
    /// Create a new instance of the database user authentication backend.
    ///
    /// # Example
    ///
    /// ```
    /// use std::sync::Arc;
    ///
    /// use cot::Project;
    /// use cot::auth::backend::AuthBackend;
    /// use cot::auth::user_pass::PasswordUserBackend;
    /// use cot::project::AuthBackendContext;
    /// # use cot::test::TestUser as MyUser;
    ///
    /// struct HelloProject;
    /// impl Project for HelloProject {
    ///     type User = MyUser;
    ///
    ///     fn auth_backends(&self, context: &AuthBackendContext) -> Vec<AuthBackend<MyUser>> {
    ///         vec![AuthBackend::UsernamePassword(Arc::new(
    ///             PasswordUserBackend::new(context.database().clone()),
    ///         ))]
    ///     }
    /// }
    /// ```
    #[must_use]
    pub fn new(database: Database) -> Self {
        Self {
            database,
            _user: PhantomData,
        }
    }
}

#[async_trait]
impl<U: CanonicalUser> AuthenticationBackendCommon<U> for PasswordUserBackend<U> {
    fn name(&self) -> &'static str {
        "cot_password_user"
    }

    async fn session_auth_hash(
        &self,
        user_id: &UserId,
        secret_key: &SecretKey,
    ) -> Result<Option<SessionAuthHash>> {
        let UserId::Int(user_id) = user_id else {
            return Err(AuthError::UserIdTypeNotSupported);
        };

        let user_password = PasswordUser::get_by_user_id(&self.database, *user_id).await?;
        Ok(user_password.map(|user_password| user_password.session_auth_hash(secret_key)))
    }
}

#[async_trait]
impl<U: CanonicalUser> UsernamePasswordBackend<U> for PasswordUserBackend<U> {
    async fn authenticate(&self, username: &str, password: &Password) -> Result<Option<UserId>> {
        let credentials = PasswordUserCredentials::new(username.to_owned(), password.clone());
        let user_password = PasswordUser::authenticate(&self.database, &credentials).await?;
        Ok(user_password.map(|user_password| UserId::Int(user_password.user_id())))
    }
}

/// An app that stores usernames and passwords of the canonical user `U` in the
/// database.
///
/// It provides the migrations for the [`PasswordUser`] model. These
/// depend on the migration that creates the table of `U`, so `U` must be a
/// model of one of the apps of the project.
pub struct PasswordUserApp<U> {
    _user: PhantomData<fn() -> U>,
}

impl<U> Debug for PasswordUserApp<U> {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("PasswordUserApp")
            .field("user", &std::any::type_name::<U>())
            .finish()
    }
}

impl<U> Clone for PasswordUserApp<U> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<U> Copy for PasswordUserApp<U> {}

impl<U> Default for PasswordUserApp<U> {
    fn default() -> Self {
        Self::new()
    }
}

impl<U> PasswordUserApp<U> {
    /// Create a new instance of the database user authentication app.
    ///
    /// # Example
    ///
    /// ```
    /// use cot::auth::user_pass::PasswordUserApp;
    /// use cot::project::RegisterAppsContext;
    /// use cot::{AppBuilder, Project};
    /// # use cot::test::TestUser as MyUser;
    ///
    /// struct HelloProject;
    /// impl Project for HelloProject {
    ///     type User = MyUser;
    ///
    ///     fn register_apps(&self, apps: &mut AppBuilder, _context: &RegisterAppsContext) {
    ///         apps.register(PasswordUserApp::<Self::User>::new());
    ///     }
    /// }
    /// ```
    #[must_use]
    pub fn new() -> Self {
        Self { _user: PhantomData }
    }
}

impl<U: CanonicalUser> App for PasswordUserApp<U> {
    fn name(&self) -> &'static str {
        "cot_password_user"
    }

    fn migrations(&self) -> Vec<Box<SyncDynMigration>> {
        migrations::migrations::<U>()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::SecretKey;

    fn test_user_password(password: &str) -> PasswordUser {
        PasswordUser {
            id: Auto::fixed(1),
            user: 1,
            username: LimitedString::new("testuser").unwrap(),
            password: PasswordHash::from_password(&Password::new(password)),
        }
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn session_auth_hash() {
        let user_password = test_user_password("password123");
        let secret_key = SecretKey::new(b"supersecretkey");

        let hash = user_password.session_auth_hash(&secret_key);
        assert_eq!(hash, user_password.session_auth_hash(&secret_key));
        assert_ne!(
            hash,
            test_user_password("password456").session_auth_hash(&secret_key)
        );
        assert_ne!(
            hash,
            user_password.session_auth_hash(&SecretKey::new(b"othersecretkey"))
        );
    }
}
